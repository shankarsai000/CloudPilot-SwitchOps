"""
AWS Read-Only Production Agent.

Autonomous read-only agent operating strictly against AWS production adapters.
Discovers inventory across 8 core services, normalizes telemetry, detects cost anomalies,
protects critical dependencies, and generates actionable GitOps-ready recommendation reports.

SAFETY INVARIANT:
Direct cloud mutation calls are unconditionally rejected with ReadOnlyViolationError.
All modifications must flow through the controlled declarative GitOps lifecycle (Phase 12).
"""

