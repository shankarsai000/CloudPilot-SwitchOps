    def discover_all_services(self) -> List[AWSResource]:
        """
        Discover live resources across all 8 supported AWS services:
        1. EC2
        2. EBS
        3. RDS
        4. VPC
        5. ELB
        6. ECS/EKS
        7. S3
        8. IAM
        """
        resources: List[AWSResource] = []

        # 1. EC2 Instances
        resources.extend(self._discover_ec2())
        # 2. EBS Volumes
        resources.extend(self._discover_ebs())
        # 3. RDS Databases
        resources.extend(self._discover_rds())
        # 4. VPC Networking
        resources.extend(self._discover_vpc())
        # 5. Elastic Load Balancers
        resources.extend(self._discover_elb())
        # 6. ECS / EKS Clusters
        resources.extend(self._discover_ecs_eks())
        # 7. S3 Storage
        resources.extend(self._discover_s3())
        # 8. IAM Security
        resources.extend(self._discover_iam())

        logger.info("Discovered %d total AWS resources across 8 services", len(resources))
        return resources

