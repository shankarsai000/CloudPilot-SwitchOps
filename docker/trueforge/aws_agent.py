logger = logging.getLogger("cloudpilot.trueforge.aws_agent")


class AWSServiceType(str, Enum):
    """Core AWS Services evaluated by the agent."""
    EC2 = "EC2"
    EBS = "EBS"
    RDS = "RDS"
    VPC = "VPC"
    ELB = "ELB"
    ECS_EKS = "ECS_EKS"
    S3 = "S3"
    IAM = "IAM"


class AWSResource(BaseModel):
    """Normalized CloudPilot canonical representation of an AWS resource."""
    resource_id: str
    name: str
    service: AWSServiceType
    resource_type: str
    region: str = "us-east-1"
    state: str = "running"
    monthly_cost_usd: float = 0.0
    utilization_metrics: Dict[str, float] = Field(default_factory=dict)
    tags: Dict[str, str] = Field(default_factory=dict)
    is_idle: bool = False
    is_oversized: bool = False
    is_critical: bool = False
    dependencies: List[str] = Field(default_factory=list)
    security_findings: List[str] = Field(default_factory=list)


class AWSCostOptimizationCandidate(BaseModel):
    """Safe, reviewed recommendation for infrastructure optimization."""
    candidate_id: str = Field(default_factory=lambda: f"cand-aws-{uuid.uuid4().hex[:6]}")
    resource_id: str
    service: AWSServiceType
    action_type: str  # rightsize, terminate_idle, archive_s3, cleanup_unattached
    current_spec: str
    target_spec: str
    current_monthly_cost: float
    target_monthly_cost: float
    estimated_monthly_savings: float
    reason: str
    blast_radius_score: float = 0.1  # 0.0 to 1.0
    gitops_remediation_hcl: str  # Declarative Terraform HCL ready for Phase 12 GitOps review


class AWSRecommendationReport(BaseModel):
    """Comprehensive analysis report generated by the AWS Read-Only Agent."""
    report_id: str = Field(default_factory=lambda: f"aws-rep-{uuid.uuid4().hex[:8]}")
    account_id: str = "123456789012"
    region: str = "us-east-1"
    agent_mode: str = "READ_ONLY"
    total_resources_discovered: int
    service_breakdown: Dict[str, int]
    total_monthly_spend_usd: float
    total_potential_monthly_savings_usd: float
    services_scanned: List[str]
    candidates: List[AWSCostOptimizationCandidate]
    protected_critical_resources: List[str]
    security_alerts: List[str]
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class AWSReadOnlyAgent:
    """
    Autonomous read-only agent for AWS.
    Safely inspects live AWS environments without any mutation capability.
    """

    def __init__(
        self,
        adapter: Optional[AWSProductionAdapter] = None,
        vault: Optional[CredentialVault] = None,
        account_id: str = "123456789012",
        region: str = "us-east-1",
    ) -> None:
        self.account_id = account_id
        self.region = region
        self.vault = vault or get_credential_vault()
        self.adapter = adapter or AWSProductionAdapter(
            mode=ProviderMode.READ_ONLY,
            vault=self.vault,
        )

        # Invariant check
        if self.adapter.mode != ProviderMode.READ_ONLY:
            raise ReadOnlyViolationError(
                provider=CloudProvider.AWS,
                capability=Capability.EXECUTE_SCALE,
                message="AWSReadOnlyAgent must be backed by an adapter in ProviderMode.READ_ONLY",
            )
        logger.info("AWSReadOnlyAgent initialized in strict READ_ONLY mode for account %s", self.account_id)

    @property
    def is_read_only(self) -> bool:
        """Enforces read-only safety invariant."""
        return True

